"""HTTP endpoints. Handlers are plain `def`s: FastAPI runs them in a thread pool, which suits
the synchronous store and model clients."""

from __future__ import annotations

from dataclasses import asdict

from fastapi import APIRouter, HTTPException, Request
from pydantic import BaseModel, Field

from app.container import Container
from app.ingest.edgar import EdgarClient, EdgarError
from app.ingest.service import IngestError

router = APIRouter(prefix="/api")


def _container(request: Request) -> Container:
    return request.app.state.container


@router.get("/filings")
def list_filings(request: Request) -> list[dict]:
    return [asdict(f) for f in _container(request).store.list_filings()]


@router.get("/filings/{filing_id}")
def get_filing(filing_id: str, request: Request) -> dict:
    store = _container(request).store
    filing = store.get_filing(filing_id)
    if filing is None:
        raise HTTPException(404, "filing not found")
    sections = [
        {"id": s.id, "item": s.item, "title": s.title, "words": len(s.text.split())}
        for s in store.list_sections(filing_id)
    ]
    return {**asdict(filing), "sections": sections}


@router.get("/sections/{section_id}")
def get_section(section_id: str, request: Request) -> dict:
    section = _container(request).store.get_section(section_id)
    if section is None:
        raise HTTPException(404, "section not found")
    return asdict(section)


class IngestRequest(BaseModel):
    source: str = Field("edgar", pattern="^(edgar|fixtures)$")
    ticker: str | None = Field(None, min_length=1, max_length=10, pattern=r"^[A-Za-z.\-]+$")
    limit: int = Field(3, ge=1, le=5)


@router.post("/filings/ingest")
def ingest(body: IngestRequest, request: Request) -> dict:
    container = _container(request)
    try:
        if body.source == "fixtures":
            results = container.ingestor.ingest_fixtures()
        else:
            if not body.ticker:
                raise HTTPException(422, "ticker is required for EDGAR ingestion")
            client = EdgarClient(container.settings.edgar_user_agent)
            results = container.ingestor.ingest_edgar(client, body.ticker, body.limit)
    except EdgarError as e:
        raise HTTPException(502, str(e)) from e
    except IngestError as e:
        raise HTTPException(422, str(e)) from e
    return {"ingested": [{"id": r.filing.id, "sections": r.sections} for r in results]}


# --- asking questions -------------------------------------------------------------------
class AskRequest(BaseModel):
    question: str = Field(..., min_length=3, max_length=500)
    strategy: str = "naive"
    tickers: list[str] | None = Field(None, max_length=10)
    years: list[int] | None = Field(None, max_length=10)


@router.get("/strategies")
def strategies() -> list[dict]:
    from app.rag.strategies import PIPELINES

    return [
        {"name": name, "title": cls.title, "description": cls.description}
        for name, cls in PIPELINES.items()
    ]


@router.post("/ask")
def ask(body: AskRequest, request: Request) -> dict:
    from app.llm.base import LlmError
    from app.models import SearchFilter
    from app.rag.strategies import PIPELINES

    pipeline_cls = PIPELINES.get(body.strategy)
    if pipeline_cls is None:
        raise HTTPException(422, f"unknown strategy: {body.strategy}")
    filt = None
    if body.tickers or body.years:
        filt = SearchFilter(
            tickers=tuple(t.upper() for t in body.tickers) if body.tickers else None,
            years=tuple(body.years) if body.years else None,
        )
    try:
        answer = pipeline_cls(_container(request).rag).run(body.question.strip(), filt)
    except LlmError as e:
        raise HTTPException(502, f"the model is unavailable: {e}") from e
    return answer_json(answer)


def answer_json(answer) -> dict:
    data = asdict(answer)
    data["retrieved"] = [
        {"chunk_id": h.chunk.id, "ticker": h.chunk.ticker, "fiscal_year": h.chunk.fiscal_year,
         "item": h.chunk.item, "kind": h.chunk.kind, "score": round(h.score, 4),
         "source": h.source, "text": h.chunk.text}
        for h in answer.retrieved
    ]
    return data


# --- evaluation ---------------------------------------------------------------------------
@router.get("/eval/report")
def eval_report(full: bool = False) -> dict:
    """The latest evaluation report (generated by `python -m app.eval.run`)."""
    import json

    from app.eval.run import REPORT_PATH

    if not REPORT_PATH.exists():
        raise HTTPException(404, "no evaluation report yet; run python -m app.eval.run")
    report = json.loads(REPORT_PATH.read_text())
    if not full:
        for data in report.get("strategies", {}).values():
            data.pop("scores", None)
    return report


# --- knowledge graph -----------------------------------------------------------------------
@router.get("/graph")
def graph(request: Request, q: str = "") -> dict:
    """Entities mentioned in `q` with the facts around them; without `q`, graph totals."""
    rag = _container(request).rag
    store = rag.store
    if not q:
        return {"entities": len(store.list_entities()), "relations": store.count_relations()}
    result = rag.graph.expand(q[:500], max_facts=20)
    return {
        "entities": [asdict(e) for e in result.mentioned],
        "bridges": result.bridge_tickers,
        "facts": [
            {"text": f.text(), "relation": f.relation.relation, "source": f.source.name,
             "target": f.target.name, "fiscal_year": f.relation.fiscal_year,
             "chunk_id": f.relation.chunk_id, "hop": f.hop}
            for f in result.facts
        ],
    }
